func TestMergeKeepsReviewed(t *testing.T) {
	previous := &File{Version: Version, Columns: []Column{
		{Schema: "s", Table: "t", Column: "email", Label: "user.contact.email", Reviewed: true},
		{Schema: "s", Table: "t", Column: "code", Label: "user.unique_id", Reviewed: false},
		{Schema: "s", Table: "gone", Column: "x", Label: "user.name", Reviewed: true},
	}}
	scanned := []Column{
		{Schema: "s", Table: "t", Column: "email", Label: None, Confidence: 0.5},
		{Schema: "s", Table: "t", Column: "code", Label: None, Confidence: 0.5},
		{Schema: "s", Table: "t", Column: "new", Label: "user.name", Confidence: 0.6},
	}
	got := (&File{Columns: Merge(previous, scanned)}).Index()
	if c := got[Key{"s", "t", "email"}]; c.Label != "user.contact.email" || !c.Reviewed {
		t.Errorf("reviewed entry overwritten: %+v", c)
	}
	if c := got[Key{"s", "t", "code"}]; c.Label != None {
		t.Errorf("unreviewed entry not refreshed: %+v", c)
	}
	if _, ok := got[Key{"s", "gone", "x"}]; !ok {
		t.Error("reviewed entry for a dropped column was lost")
	}
	if _, ok := got[Key{"s", "t", "new"}]; !ok {
		t.Error("new column missing")
	}
}

func TestSaveLoad(t *testing.T) {
	path := t.TempDir() + "/c.yaml"
	f := &File{Version: Version, Source: Source{Engine: "postgres", Database: "db", ScannedAt: time.Date(2026, 10, 18, 0, 0, 0, 0, time.UTC)},
		Columns: []Column{{Schema: "s", Table: "b", Column: "x", Label: None}, {Schema: "s", Table: "a", Column: "y", Label: "user.name", Evidence: []string{"name"}}}}
	if err := Save(path, f); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(path)
	if !strings.HasPrefix(string(data), "# Generated by maskplan scan") {
		t.Errorf("missing header:\n%s", data)
	}
	g, err := Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(g.Columns) != 2 || g.Columns[0].Table != "a" || g.Source.Database != "db" {
		t.Errorf("round trip: %+v", g)
	}
	os.WriteFile(path, []byte("version: 2\n"), 0o644)
	if _, err := Load(path); err == nil {
		t.Error("loaded an unsupported version")
	}
}
