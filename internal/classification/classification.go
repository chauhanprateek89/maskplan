// Package classification reads and writes classification.yaml: the label
// maskplan assigns to every column it scanned. People review and commit the
// file; entries marked reviewed are never overwritten by a later scan.
package classification

import (
	"fmt"
	"os"
	"sort"
	"time"

	"gopkg.in/yaml.v3"
)

// Version is the file format version.
const Version = 1

// None is the label for a column that holds no personal data.
const None = "none"

// FreeText is the label for text columns that may contain personal data in
// prose (notes, comments). Treated as PII.
const FreeText = "free_text"

// File is the layout of classification.yaml.
type File struct {
	Version int      `yaml:"version"`
	Source  Source   `yaml:"source"`
	Columns []Column `yaml:"columns"`
}

// Source records where and when the scan ran.
type Source struct {
	Engine    string    `yaml:"engine"`
	Database  string    `yaml:"database"`
	ScannedAt time.Time `yaml:"scanned_at"`
}

// Column is one classified column.
type Column struct {
	Schema     string   `yaml:"schema"`
	Table      string   `yaml:"table"`
	Column     string   `yaml:"column"`
	Type       string   `yaml:"type"`
	Label      string   `yaml:"label"`
	Confidence float64  `yaml:"confidence"`
	Evidence   []string `yaml:"evidence,omitempty"`
	// DerivedFrom names the column in the same table this one holds tokens
	// of (email_tok of email). It carries the source's label. The report
	// does not count it as masked until it can verify what fills it.
	DerivedFrom string `yaml:"derived_from,omitempty"`
	Reviewed    bool   `yaml:"reviewed"`
}

// Key identifies a column.
type Key struct{ Schema, Table, Column string }

func (c Column) Key() Key { return Key{c.Schema, c.Table, c.Column} }

func (k Key) String() string { return k.Schema + "." + k.Table + "." + k.Column }

// IsPII reports whether the label marks personal data.
func (c Column) IsPII() bool { return c.Label != "" && c.Label != None }

// Index maps columns by key.
func (f *File) Index() map[Key]Column {
	m := make(map[Key]Column, len(f.Columns))
	for _, c := range f.Columns {
		m[c.Key()] = c
	}
	return m
}

// Load reads a classification file.
func Load(path string) (*File, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var f File
	if err := yaml.Unmarshal(data, &f); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if f.Version != Version {
		return nil, fmt.Errorf("%s: unsupported version %d, want %d", path, f.Version, Version)
	}
	return &f, nil
}

// Save writes f with columns in a stable order, so diffs stay reviewable.
func Save(path string, f *File) error {
	sort.Slice(f.Columns, func(i, j int) bool {
		a, b := f.Columns[i], f.Columns[j]
		if a.Schema != b.Schema {
			return a.Schema < b.Schema
		}
		if a.Table != b.Table {
			return a.Table < b.Table
		}
		return a.Column < b.Column
	})
	data, err := yaml.Marshal(f)
	if err != nil {
		return err
	}
	header := "# Generated by maskplan scan. Review every label, set reviewed: true on the\n" +
		"# entries you have checked, and commit this file. Reviewed entries are kept\n" +
		"# as they are by later scans.\n"
	return os.WriteFile(path, append([]byte(header), data...), 0o644)
}

// Merge returns the scanned columns, with every reviewed entry from previous
// kept as it was. Reviewed entries for columns that no longer exist are kept
// too, so a dropped and re-added column does not silently lose its review.
func Merge(previous *File, scanned []Column) []Column {
	if previous == nil {
		return scanned
	}
	reviewed := map[Key]Column{}
	for _, c := range previous.Columns {
		if c.Reviewed {
			reviewed[c.Key()] = c
		}
	}
	out := make([]Column, 0, len(scanned))
	for _, c := range scanned {
		if r, ok := reviewed[c.Key()]; ok {
			c = r
			delete(reviewed, c.Key())
		}
		out = append(out, c)
	}
	for _, r := range reviewed {
		out = append(out, r)
	}
	return out
}
